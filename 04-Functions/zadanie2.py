# laduje modul math zeby miec dostep do funkcji matematycznych
import math

# licze pierwiastek kwadratowy z 7
square_root = math.sqrt(7)
print('A square root of 7 is', square_root)

# licze logarytm naturalny z 5
natural_log = math.log(5)
print('Natural logarithm of 5 is', natural_log)

# zamieniam 90 stopni na radiany i dopiero wtedy licze sinus
sine_90 = math.sin(math.radians(90))
print('Sine of 90 degrees is', sine_90)